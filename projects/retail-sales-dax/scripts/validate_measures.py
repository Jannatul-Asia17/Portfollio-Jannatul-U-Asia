"""
Re-computes the project's key DAX measures in pandas and writes the answers to
docs/expected_results.md.

Why: a DAX measure can be syntactically valid and still wrong (wrong filter
context, wrong relationship, double counting). Having an independent answer key
lets you check every card and visual in Power BI against known-good numbers.

The cleaning below mirrors the Power Query steps in ../powerquery exactly.

Run:  python scripts/validate_measures.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA, OUT = ROOT / "data", ROOT / "docs" / "expected_results.md"


def load():
    # --- Power Query: FactSales (remove duplicates, fix casing) ------------
    fact = pd.read_csv(DATA / "fact_sales.csv", parse_dates=["OrderDate", "ShipDate"])
    raw_rows = len(fact)
    fact = fact.drop_duplicates()
    fact["ShipMode"] = fact["ShipMode"].str.strip().str.title()
    fact["DaysToShip"] = (fact["ShipDate"] - fact["OrderDate"]).dt.days

    # DAX calculated column: Discount Band
    def band(d):
        if d == 0: return "0%"
        if d <= 0.10: return "1-10%"
        if d <= 0.20: return "11-20%"
        if d <= 0.30: return "21-30%"
        return "Over 30%"
    fact["DiscountBand"] = fact["Discount"].map(band)

    # --- Power Query: dimensions ------------------------------------------
    cust = pd.read_csv(DATA / "dim_customer.csv")
    cust["CustomerName"] = cust["CustomerName"].str.strip()
    prod = pd.read_csv(DATA / "dim_product.csv")
    geo = pd.read_csv(DATA / "dim_geography.csv")
    returns = pd.read_csv(DATA / "returns.csv")
    targets = pd.read_csv(DATA / "targets.csv", parse_dates=["MonthStart"])

    df = (fact.merge(prod, on="ProductID", how="left")
              .merge(geo, on="GeographyKey", how="left")
              .merge(cust, on="CustomerID", how="left"))
    df["Year"] = df["OrderDate"].dt.year
    df["MonthStart"] = df["OrderDate"].dt.to_period("M").dt.to_timestamp()
    df["Returned"] = df["OrderID"].isin(set(returns["OrderID"]))
    return df, targets, raw_rows


def kpis(g: pd.DataFrame) -> pd.Series:
    """Base measures, evaluated over whatever rows are 'in filter context'."""
    sales, cost = g["Sales"].sum(), g["Cost"].sum()
    orders = g["OrderID"].nunique()
    returned = g.loc[g["Returned"], "OrderID"].nunique()
    return pd.Series({
        "Total Sales": sales,
        "Total Profit": sales - cost,
        "Profit Margin %": (sales - cost) / sales if sales else None,
        "Orders": orders,
        "Units Sold": g["Quantity"].sum(),
        "Customers": g["CustomerID"].nunique(),
        "Avg Order Value": sales / orders if orders else None,
        "Discount %": (g["GrossSales"].sum() - sales) / g["GrossSales"].sum(),
        "Return Rate %": returned / orders if orders else None,
    })


COUNTS = {"Loss-making Orders", "Orders", "Units Sold", "Customers", "New Customers", "Returning Customers", "Repeat Customers", "Rank"}


def fmt(v, name):
    """Format a value the way the matching DAX measure's format string would."""
    if pd.isna(v):
        return "(blank)"
    if name.endswith("%") or name.startswith("%"):
        return f"{v:.1%}"
    if name in COUNTS:
        return f"{int(v):,}"
    return f"{v:,.2f}"


def md_table(df: pd.DataFrame, index_name: str) -> str:
    df = df.reset_index()
    if pd.api.types.is_numeric_dtype(df.iloc[:, 0]):
        df[df.columns[0]] = df.iloc[:, 0].astype(int).astype(str)
    df.columns = [index_name] + list(df.columns[1:])
    head = "| " + " | ".join(df.columns) + " |"
    sep = "|" + "|".join(["---"] + ["---:"] * (len(df.columns) - 1)) + "|"
    # In a one-column table each row is a different measure, so format by row name
    by_row = len(df.columns) == 2 and index_name == "Measure"
    rows = ["| " + " | ".join([str(r[df.columns[0]])] +
                              [fmt(r[c], r[df.columns[0]] if by_row else c) for c in df.columns[1:]]) + " |"
            for _, r in df.iterrows()]
    return "\n".join([head, sep, *rows])


def main():
    df, targets, raw_rows = load()
    out = ["# Expected results (answer key)", "",
           "Generated by `scripts/validate_measures.py`, an independent pandas re-implementation of the DAX measures.",
           "Once the model is built, every number here should match the same visual in Power BI.",
           "If one doesn't, the filter context or a relationship is wrong.", "",
           f"Data quality: {raw_rows:,} raw fact rows → **{len(df):,} rows** after removing "
           f"{raw_rows - len(df):,} exact duplicates in Power Query.", ""]

    # 1. Overall cards
    overall = kpis(df).to_frame("All years")
    out += ["## 1. KPI cards (no filters)", "", md_table(overall, "Measure"), ""]

    # 2. By year + time intelligence
    by_year = df.groupby("Year").apply(kpis, include_groups=False)
    by_year["Sales PY"] = by_year["Total Sales"].shift(1)
    by_year["YoY %"] = by_year["Total Sales"] / by_year["Sales PY"] - 1
    by_year["Profit YoY %"] = by_year["Total Profit"] / by_year["Total Profit"].shift(1) - 1
    first = df.groupby("CustomerID")["OrderDate"].min().dt.year
    by_year["New Customers"] = first.value_counts().sort_index()
    by_year["Returning Customers"] = by_year["Customers"] - by_year["New Customers"]
    rep = df.groupby(["Year", "CustomerID"])["OrderID"].nunique()
    by_year["Repeat Customers"] = (rep > 1).groupby(level=0).sum()
    cols = ["Total Sales", "Sales PY", "YoY %", "Total Profit", "Profit YoY %", "Profit Margin %",
            "Orders", "Avg Order Value", "Customers", "New Customers", "Returning Customers",
            "Repeat Customers", "Return Rate %"]
    out += ["## 2. By year: time intelligence & customers", "",
            "`Sales PY` uses SAMEPERIODLASTYEAR; `New Customers` = first-ever order falls in the year.", "",
            md_table(by_year[cols], "Year"), ""]

    # 3. YTD in Dec / rolling 3M at end of 2025
    m = df.groupby("MonthStart")["Sales"].sum()
    m25 = m[m.index.year == 2025]
    ytd = m25.cumsum()
    roll3 = m.rolling(3).sum()
    tbl = pd.DataFrame({"Total Sales": m25, "Sales YTD": ytd, "Sales Rolling 3M": roll3[m25.index],
                        "MoM %": m.pct_change()[m25.index]})
    tbl.index = tbl.index.strftime("%Y-%m")
    out += ["## 3. Monthly 2025: YTD, rolling 3 months, MoM", "", md_table(tbl, "Month"), ""]

    # 4. Region
    reg = df.groupby("Region").apply(kpis, include_groups=False).sort_values("Total Sales", ascending=False)
    out += ["## 4. By region", "", md_table(reg[["Total Sales", "Total Profit", "Profit Margin %",
                                                   "Discount %", "Return Rate %"]], "Region"), ""]

    # 5. Category x Region margin (matrix visual)
    mat = df.groupby(["Category", "Region"]).apply(
        lambda g: (g["Sales"].sum() - g["Cost"].sum()) / g["Sales"].sum(), include_groups=False).unstack()
    mat.columns = [f"{c} margin %" for c in mat.columns]
    out += ["## 5. Profit margin %: Category × Region matrix", "", md_table(mat, "Category"), ""]

    # 6. Discount band
    order = ["0%", "1-10%", "11-20%", "21-30%", "Over 30%"]
    disc = df.groupby("DiscountBand").apply(kpis, include_groups=False).reindex(order)
    disc["Share of Sales %"] = disc["Total Sales"] / disc["Total Sales"].sum()
    out += ["## 6. By discount band (calculated column)", "",
            md_table(disc[["Total Sales", "Share of Sales %", "Total Profit", "Profit Margin %"]], "Discount Band"), ""]

    # 6b. Profitability measures + what-if parameter
    order_profit = df.groupby("OrderID").apply(lambda g: g["Sales"].sum() - g["Cost"].sum(), include_groups=False)
    deep = df["Discount"] > 0.20
    prof = {
        "Loss-making Orders": int((order_profit < 0).sum()),
        "Loss-making Orders %": (order_profit < 0).mean(),
        "Deep-Discount Sales %": df.loc[deep, "Sales"].sum() / df["Sales"].sum(),
        "Profit at Deep Discount": df.loc[deep, "Sales"].sum() - df.loc[deep, "Cost"].sum(),
    }
    for cap in (0.30, 0.20, 0.10):
        sim = (df["GrossSales"] * (1 - df["Discount"].clip(upper=cap)) - df["Cost"]).sum()
        prof[f"Simulated Profit @ {cap:.0%} cap"] = sim
    prof_tbl = pd.Series(prof).to_frame("All years")
    out += ["### Profitability measures and the *Discount Cap* what-if parameter", "",
            "Simulated profit assumes the same orders would still happen with a smaller discount "
            "(an upper bound, worth saying out loud in an interview).", "",
            md_table(prof_tbl, "Measure"), ""]

    # 7. Sub-category, loss makers
    sub = df.groupby(["Category", "SubCategory"]).apply(kpis, include_groups=False)
    sub = sub.sort_values("Total Profit")
    sub.index = [f"{c} / {s}" for c, s in sub.index]
    out += ["## 7. Sub-categories ranked by profit", "",
            md_table(sub[["Total Sales", "Total Profit", "Profit Margin %", "Discount %"]], "Sub-category"), ""]

    # 8. Top 10 products + Pareto
    p = df.groupby("ProductName")["Sales"].sum().sort_values(ascending=False)
    top = pd.DataFrame({"Total Sales": p, "Rank": range(1, len(p) + 1), "Cumulative %": p.cumsum() / p.sum()})
    n80 = int((top["Cumulative %"] < 0.80).sum()) + 1
    out += ["## 8. Top 10 products (RANKX) and Pareto", "", md_table(top.head(10), "Product"), "",
            f"Pareto: **{n80} of {len(p)} products ({n80 / len(p):.0%})** generate 80% of sales "
            f"(`[Products for 80% of Sales]` = {n80}). "
            f"`[Top N Sales]` with N = 10: {p.head(10).sum():,.2f} "
            f"(`[Top N Share %]` = {p.head(10).sum() / p.sum():.1%}).", ""]

    # 9. Targets (virtual relationship via TREATAS)
    act = df.groupby([df["MonthStart"], "Region", "Category"])["Sales"].sum().rename("Actual").reset_index()
    t = targets.merge(act, on=["MonthStart", "Region", "Category"], how="left")
    t["Year"] = t["MonthStart"].dt.year
    ty = t.groupby("Year")[["Actual", "SalesTarget"]].sum()
    ty["Variance"] = ty["Actual"] - ty["SalesTarget"]
    ty["% of Target"] = ty["Actual"] / ty["SalesTarget"]
    ty.columns = ["Total Sales", "Sales Target", "Variance", "% of Target"]
    tr = t[t["Year"] == 2025].groupby("Region")[["Actual", "SalesTarget"]].sum()
    tr["% of Target"] = tr["Actual"] / tr["SalesTarget"]
    tr.columns = ["Total Sales", "Sales Target", "% of Target"]
    out += ["## 9. Sales vs target (TREATAS virtual relationship)", "", md_table(ty, "Year"), "",
            "2025 by region:", "", md_table(tr.sort_values("% of Target"), "Region"), ""]

    # 10. Shipping
    ship = df.groupby("ShipMode").agg(**{"Orders": ("OrderID", "nunique"), "Avg Days to Ship": ("DaysToShip", "mean")})
    out += ["## 10. Shipping (USERELATIONSHIP / calculated column)", "", md_table(ship, "Ship Mode"), "",
            f"Sales by **ship** date in 2025 (inactive relationship): "
            f"{df.loc[df['ShipDate'].dt.year == 2025, 'Sales'].sum():,.2f}", ""]

    # 11. Headline insight for 2025
    d25, d24 = df[df["Year"] == 2025], df[df["Year"] == 2024]
    yoy = d25["Sales"].sum() / d24["Sales"].sum() - 1
    top_region = d25.groupby("Region")["Sales"].sum().idxmax()
    sub_m = d25.groupby("SubCategory").apply(lambda g: 1 - g["Cost"].sum() / g["Sales"].sum(), include_groups=False)
    headline = (f"Sales of ${d25['Sales'].sum():,.0f}, {'up' if yoy >= 0 else 'down'} {abs(yoy):.1%} on last year. "
                f"{top_region} is the largest region; {sub_m.idxmin()} has the thinnest margin.")
    out += ["## 11. `[Headline Insight]` with Year = 2025", "", f"> {headline}", ""]

    OUT.write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
